"""Trace every number in the README to a file under results/.

Reads README.md, pulls out each number in the prose and tables, and looks for the same
number in the generated files under results/. Writes results/readme_numbers.md with
one row per number. Exits with an error if any number has no source.

    python scripts/check_readme.py
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Numbers that are settings or facts about the world, not results, with where they come from.
KNOWN = {
    "2017": "year of the dataset paper (MMSys 2017)",
    "360": "a full turn in degrees, as in 360-degree video",
    "100": "the viewer's window is 100 degrees wide, a setting in src/geometry.py",
}
NUMBER = re.compile(r"(?<![\w.])[+\-]?\d[\d,]*(?:\.\d+)?%?")
SOURCES = ("baselines.md", "chosen_vs_random.md", "four_vs_sixteen.md", "why_not_mixed.md", "style_check.md",
           "budget.md", "data_summary.md", "id_linkage.md", "demo.md")


def strip_non_prose(text: str) -> str:
    """Drop code blocks, HTML comments, link targets and inline code."""
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"<!--.*?-->", " ", text, flags=re.S)
    text = re.sub(r"\]\([^)]*\)", "]", text)
    text = re.sub(r"`[^`]*`", " ", text)
    return re.sub(r"https?://\S+", " ", text)


def normalise(token: str) -> str:
    """'+0.33', '0.33%' and '1,000' compare equal to '0.33' and '1000'. The sign of a
    negative number is kept."""
    return token.replace(",", "").rstrip("%").lstrip("+").rstrip(".")


def numbers_in(text: str) -> list[str]:
    return [m.group(0).rstrip(",.") for m in NUMBER.finditer(text)]


def trace(readme: str, results: dict[str, str]) -> list[dict]:
    """One row per distinct README number: where it was found, or nothing."""
    found = {name: {normalise(t) for t in numbers_in(text)} for name, text in results.items()}
    rows, seen = [], set()
    for token in numbers_in(strip_non_prose(readme)):
        key = normalise(token)
        if key in seen:
            continue
        seen.add(key)
        if key in KNOWN:
            rows.append({"number": token, "source": KNOWN[key], "ok": True})
            continue
        files = [name for name in results if key in found[name]]
        rows.append({"number": token, "source": ", ".join(f"results/{f}" for f in files), "ok": bool(files)})
    return rows


def to_markdown(rows: list[dict], words: int) -> str:
    lines = [
        "# Where each README number comes from",
        "",
        "Generated by `scripts/check_readme.py`. A number is traced when the same number",
        "appears in a generated file under `results/`.",
        "",
        f"README length: {words} words.",
        "",
        "| Number in the README | Found in |",
        "|---|---|",
    ]
    lines += [f"| {r['number']} | {r['source'] if r['ok'] else 'NOT FOUND'} |" for r in rows]
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--readme", default="README.md")
    p.add_argument("--results-dir", default="results")
    args = p.parse_args(argv)
    readme = Path(args.readme).read_text(encoding="utf-8")
    results = {name: (Path(args.results_dir) / name).read_text(encoding="utf-8") for name in SOURCES}
    rows = trace(readme, results)
    words = len(strip_non_prose(readme).split())
    md = to_markdown(rows, words)
    (Path(args.results_dir) / "readme_numbers.md").write_text(md, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(md.encode("utf-8"))
    missing = [r["number"] for r in rows if not r["ok"]]
    if missing:
        print(f"\nNOT TRACED: {missing}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
